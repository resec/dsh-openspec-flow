/**
 * `openspec_init`: create the project structure and install the plugin skills.
 *
 * The CLI creates `openspec/config.yaml` and `openspec/specs/` with
 * `init --tools none`, so no official skill is generated. The plugin then
 * writes its six skills into `.dsh/skills/` and migrates same-named official
 * copies after backing them up.
 *
 * @module dsh-openspec-flow/init
 */

import { accessSync, constants, existsSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { runOpenSpecCommand } from './openspec.js'
import { installSkills, isDirectory } from './skills.js'
import { renderJson, sessionCwd } from './tools/shared.js'

/**
 * Register `openspec_init`.
 * @param ctx - host context.
 * @param settings - resolved plugin settings.
 * @returns nothing.
 */
export function registerInitTool(ctx, settings) {
  ctx.effect(() => ctx.tools.register({
    name: 'openspec_init',
    description: 'Initialize an OpenSpec project for this plugin: create openspec/config.yaml and openspec/specs/ with the CLI, then write six plugin skills into .dsh/skills/ and migrate official skills after backing them up. Never runs automatically; call it only when the user asks.',
    parameters: {
      type: 'object',
      additionalProperties: false,
      properties: {
        path: {
          type: 'string',
          description: 'Project directory; defaults to the session working directory.',
        },
        force: {
          type: 'boolean',
          description: 'Replace same-named skills that were not generated by OpenSpec or this plugin. Backed up first.',
        },
      },
    },
    output: {
      schema: {
        type: 'object',
        additionalProperties: false,
        required: ['root', 'config', 'skills'],
        properties: {
          root: { type: 'string' },
          config: {
            type: 'string',
            enum: ['created', 'exists'],
            description: 'created means this call ran init; exists means config.yaml was already present.',
          },
          skills: {
            type: 'object',
            additionalProperties: false,
            required: ['written', 'migrated', 'skipped', 'conflicts'],
            properties: {
              written: { type: 'array', items: { type: 'string' } },
              migrated: { type: 'array', items: { type: 'string' } },
              skipped: { type: 'array', items: { type: 'string' } },
              conflicts: {
                type: 'array',
                items: {
                  type: 'object',
                  additionalProperties: false,
                  required: ['name', 'path', 'generatedBy'],
                  properties: {
                    name: { type: 'string' },
                    path: { type: 'string' },
                    generatedBy: { type: 'string' },
                  },
                },
              },
            },
          },
          backupDir: { type: 'string' },
        },
      },
      render: renderJson,
    },
    async execute(args, exec) {
      const cwd = await sessionCwd(ctx, exec)
      const target = typeof args?.path === 'string' && args.path.trim() !== ''
        ? resolve(cwd, args.path.trim())
        : cwd
      if (!isDirectory(target)) {
        throw new Error(`openspec_init target '${target}' is not a directory.`)
      }
      try {
        accessSync(target, constants.W_OK)
      } catch {
        throw new Error(`openspec_init cannot write to '${target}'. Check the directory permissions and retry.`)
      }

      const configPath = join(target, 'openspec', 'config.yaml')
      const configAltPath = join(target, 'openspec', 'config.yml')
      let config = 'exists'
      if (!existsSync(configPath) && !existsSync(configAltPath)) {
        await runOpenSpecCommand(
          ctx,
          settings,
          target,
          ['init', '--tools', 'none', '--no-animation'],
          exec.signal,
        )
        config = 'created'
      }

      const installed = installSkills(target, {
        force: args?.force === true,
      })
      return {
        root: target,
        config,
        skills: {
          written: installed.written,
          migrated: installed.migrated,
          skipped: installed.skipped,
          conflicts: installed.conflicts.map((conflict) => ({
            name: conflict.name,
            path: conflict.path,
            generatedBy: String(conflict.generatedBy ?? ''),
          })),
        },
        ...(installed.backupDir !== undefined ? { backupDir: installed.backupDir } : {}),
      }
    },
  }))
}
